import fs from 'node:fs';
import path from 'node:path';

const SRC_DIR =
  process.argv[2] ||
  process.env.JAVA_SRC_DIR ||
  process.env.SRC_DIR ||
  '/Users/kshaikh/git/java/patterns/APIGateway/src/main/java/com/artificialintelligence/patterns/apigateway';
const OUT_FILE = '/Users/kshaikh/git/typescript/monaco/src/javaFiles.ts';

const files = fs.readdirSync(SRC_DIR)
  .filter(f => f.endsWith('.java'))
  .sort();

const entries = files.map(f => {
  const content = fs.readFileSync(path.join(SRC_DIR, f), 'utf8');
  return { name: f, content };
});

const ts = `// Auto-generated by scripts/gen-java-files.mjs. Do not edit.
export interface JavaFile {
  name: string;
  content: string;
}

export const javaFiles: JavaFile[] = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(OUT_FILE, ts, 'utf8');
console.log(`Generated ${entries.length} files -> ${OUT_FILE}`);