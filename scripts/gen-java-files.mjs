import fs from 'node:fs';
import path from 'node:path';

const HELP = `Usage: node scripts/gen-java-files.mjs [path|--path=<path>|--src=<path>|--dir=<path>]

Generates src/javaFiles.ts from every file in a directory (recursively), skipping only .git.

Options:
  <path>            Source directory
  --path, --src, --dir <path>   Source directory (flag form)
  --path=<path> etc.            Source directory (equals form)
  -h, --help                    Show this help

Environment variables:
  JAVA_SRC_DIR, SRC_DIR, SOURCE_DIR   Source directory (used if no CLI arg)

Default source directory:
  (current working directory)
`;

if (process.argv.includes('-h') || process.argv.includes('--help')) {
  process.stdout.write(HELP);
  process.exit(0);
}

function resolveSrcPath(argv) {
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--path=') || a.startsWith('--src=') || a.startsWith('--dir=')) {
      return a.split('=').slice(1).join('=');
    }
    if (a === '--path' || a === '--src' || a === '--dir') {
      return argv[++i];
    }
    if (!a.startsWith('--')) {
      return a;
    }
  }
  return process.env.JAVA_SRC_DIR || process.env.SRC_DIR || process.env.SOURCE_DIR;
}

const resolved = resolveSrcPath(process.argv);
const SRC_DIR =
  resolved || process.cwd();
const OUT_FILE = '/Users/kshaikh/git/typescript/monaco/src/javaFiles.ts';

const SKIP_DIRS = new Set(['.git', 'target', 'out', '.target', '.out', 'node_modules', 'dist', 'build']);

function walkJava(dir, base) {
  const result = [];
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return result;
  }
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      result.push(...walkJava(full, base));
    } else if (e.isFile()) {
      const lower = e.name.toLowerCase();
      if (e.name === '.DS_Store' || lower.endsWith('.png')) continue;
      const rel = path.relative(base, full).split(path.sep).join('/');
      result.push({ rel, full });
    }
  }
  return result;
}

const found = walkJava(SRC_DIR, SRC_DIR).sort((a, b) => a.rel.localeCompare(b.rel));

const entries = found.map(({ rel, full }) => {
  const content = fs.readFileSync(full, 'utf8');
  return { name: rel, content };
});

const ts = `// Auto-generated by scripts/gen-java-files.mjs. Do not edit.
export interface JavaFile {
  name: string;
  content: string;
}

export const javaFiles: JavaFile[] = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(OUT_FILE, ts, 'utf8');
console.log(`Generated ${entries.length} files -> ${OUT_FILE}`);